export type Locale = 'en' | 'zh'

function initial(): Locale {
  try {
    const saved = localStorage.getItem('kube-bmc.locale')
    if (saved === 'en' || saved === 'zh') return saved
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const locale = ref<Locale>(initial())

export function setLocale(l: Locale) {
  locale.value = l
  try {
    localStorage.setItem('kube-bmc.locale', l)
  } catch {
    /* storage unavailable */
  }
}

const dict = computed(() => (locale.value === 'zh' ? zh : en))

export function t(key: Key | string, vars?: Record<string, string>): string {
  let s = (dict.value as Record<string, string>)[key] ?? key
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replace(`{${k}}`, v)
  return s
}
